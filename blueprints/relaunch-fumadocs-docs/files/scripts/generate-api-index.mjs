// Generate the HTTP API index page from the OpenAPI documents the site renders.
//
//   bun scripts/generate-api-index.mjs           writes content/docs/<apiBaseDir>/index.mdx
//   bun scripts/generate-api-index.mjs --check   fails if the page differs from its generator
//
// fumadocs-openapi renders one page per operation and no index, so /docs/<apiBaseDir>
// is otherwise a 404. The documents are read from the directory named by the fumadocs
// module's docs.openapi-spec (docs-gates.json "openapiDir"). Keep those snapshots in
// step with the pinned revision, for example with a sync script and its --check mode.
// Wording comes from docs-gates.json "apiIndex": { title, description, intro }.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"

import { docsRoot, openapiDocuments, openapiOperations, pin, settings } from "./doc-pages.mjs"

const check = process.argv.includes("--check")
const name = pin?.name ?? "the project"
const revisionText = pin?.revision ? ` at revision \`${pin.revision.slice(0, 12)}\`` : ""

function escapeMdx(text) {
  return text
    .split(/(`[^`]*`)/)
    .map((part, index) =>
      index % 2 === 1 ? part : part.replaceAll("{", "\\{").replaceAll("<", "&lt;"),
    )
    .join("")
}

function apiIndexPage() {
  const documents = openapiDocuments()
  if (!documents.length) {
    console.error(`No OpenAPI documents in ${settings.openapiDir}/.`)
    process.exit(2)
  }
  const several = documents.length > 1
  const rows = [...openapiOperations().values()].toSorted(
    (a, b) => a.path.localeCompare(b.path, "en") || a.method.localeCompare(b.method, "en"),
  )
  const {
    title = "HTTP API operations",
    description = `Every operation of the ${name} HTTP API, generated from its OpenAPI ${several ? "documents" : "document"}.`,
    intro = `This page is generated from ${name}'s OpenAPI ${several ? `documents (${documents.map((d) => `\`${d.name}\``).join(", ")})` : "document"}${revisionText}.`,
  } = settings.apiIndex
  const lines = [
    "---",
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    "{/* Generated by scripts/generate-api-index.mjs. Do not edit. */}",
    "",
    intro,
    "",
    several ? "| Operation | Path | Document | Summary |" : "| Operation | Path | Summary |",
    several ? "| --- | --- | --- | --- |" : "| --- | --- | --- |",
  ]
  for (const { id, method, path, summary, documents: declaredIn } of rows) {
    const text = escapeMdx(summary.replaceAll("|", "\\|").replaceAll("\n", " "))
    const link = `[${method}](/docs/${settings.apiBaseDir}/${id})`
    lines.push(
      several
        ? `| ${link} | \`${path}\` | ${declaredIn.join(", ")} | ${text} |`
        : `| ${link} | \`${path}\` | ${text} |`,
    )
  }
  lines.push("")
  return lines.join("\n")
}

const file = join(docsRoot, settings.apiBaseDir, "index.mdx")
const contents = apiIndexPage()
if (check) {
  if (!existsSync(file) || readFileSync(file, "utf8") !== contents) {
    console.error(
      `content/docs/${settings.apiBaseDir}/index.mdx does not match its generator. Run: bun run gen:api-index`,
    )
    process.exit(1)
  }
  console.log("Generated API index OK.")
} else {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, contents)
  console.log(`wrote content/docs/${settings.apiBaseDir}/index.mdx`)
}
